#!/bin/bash
# IBM MAS-Manage-UI JMeter soak. Intended to run inside the idle bench pod:
#   oc exec deploy/mas-vpa-bench -- /opt/benchmark/run.sh 86400
set -euo pipefail

if [[ $# -lt 1 ]]; then
  echo "usage: run.sh <duration-seconds>" >&2
  echo "example: /opt/benchmark/run.sh 86400" >&2
  exit 2
fi
DURATION_S="$1"

: "${USER_PASSWORD:?set USER_PASSWORD (oc create secret / oc set env --from=secret)}"
: "${MAS_DOMAIN:?set MAS_DOMAIN, e.g. mas1.apps.rosa.example.com}"

MAS_WORKSPACE="${MAS_WORKSPACE:-ws1}"
HEAP="${HEAP:-1g}"
THINK_TIME="${THINK_TIME:-15000}"
USER_DELAY_MILLISECONDS="${USER_DELAY_MILLISECONDS:-5000}"
THREADGROUP_LOOPS="${THREADGROUP_LOOPS:--1}"

VIEWLOCATION_USERS="${VIEWLOCATION_USERS:-3}"
VIEWPURCHASE_USERS="${VIEWPURCHASE_USERS:-1}"
VIEWPURCHASE_USERS_CHG="${VIEWPURCHASE_USERS_CHG:-1}"
VIEWPURCHASE_USERS_RCV="${VIEWPURCHASE_USERS_RCV:-1}"
VIEWPURCHASE_USERS_CL="${VIEWPURCHASE_USERS_CL:-1}"
VIEWWORKORDER_USERS="${VIEWWORKORDER_USERS:-2}"
VIEWWORKORDER_USERS_VA="${VIEWWORKORDER_USERS_VA:-1}"
VIEWWORKORDER_USERS_INP="${VIEWWORKORDER_USERS_INP:-0}"
VIEWWORKORDER_USERS_COMP="${VIEWWORKORDER_USERS_COMP:-1}"
VIEWWORKORDER_USERS_CL="${VIEWWORKORDER_USERS_CL:-1}"

PROPS="/tmp/bench.properties"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
OUT="/tmp/run-${STAMP}.jtl"
LOG="/tmp/run-${STAMP}.log"

cat > "$PROPS" <<EOF
MAS_DOMAIN=${MAS_DOMAIN}
MAS_WORKSPACE=${MAS_WORKSPACE}
USER_PASSWORD=${USER_PASSWORD}
CONNECT_TIMEOUT=60000
RESPONSE_TIMEOUT=60000
THREADGROUP_LOOPS=${THREADGROUP_LOOPS}
USER_DELAY_MILLISECONDS=${USER_DELAY_MILLISECONDS}
THINK_TIME=${THINK_TIME}
RAMPUP_ASSETS_PERIOD_SECONDS=${RAMPUP_ASSETS_PERIOD_SECONDS:-120}
RAMPUP_PR_PERIOD_SECONDS=${RAMPUP_PR_PERIOD_SECONDS:-120}
RAMPUP_WO_PERIOD_SECONDS=${RAMPUP_WO_PERIOD_SECONDS:-180}
LOCATION_LOOPS=${LOCATION_LOOPS:-12}
PURCHASE_LOOPS=${PURCHASE_LOOPS:-12}
WORKORDER_LOOPS=${WORKORDER_LOOPS:-12}
VIEWLOCATION_USERS=${VIEWLOCATION_USERS}
VIEWPURCHASE_USERS=${VIEWPURCHASE_USERS}
VIEWPURCHASE_USERS_CHG=${VIEWPURCHASE_USERS_CHG}
VIEWPURCHASE_USERS_RCV=${VIEWPURCHASE_USERS_RCV}
VIEWPURCHASE_USERS_CL=${VIEWPURCHASE_USERS_CL}
VIEWWORKORDER_USERS=${VIEWWORKORDER_USERS}
VIEWWORKORDER_USERS_VA=${VIEWWORKORDER_USERS_VA}
VIEWWORKORDER_USERS_INP=${VIEWWORKORDER_USERS_INP}
VIEWWORKORDER_USERS_COMP=${VIEWWORKORDER_USERS_COMP}
VIEWWORKORDER_USERS_CL=${VIEWWORKORDER_USERS_CL}
VIEWLOCATION_USER_PREFIX=asset
VIEWPURCHASE_USER_PREFIX=pocrt
VIEWPURCHASE_USER_CHG_PREFIX=pochng
VIEWPURCHASE_USER_RCV_PREFIX=porcv
VIEWPURCHASE_USER_CL_PREFIX=pocls
VIEWWORKORDER_USER_PREFIX=wocrt
VIEWWORKORDER_USER_VA_PREFIX=woappr
VIEWWORKORDER_USER_INP_PREFIX=wfissue
VIEWWORKORDER_USER_COMP_PREFIX=wfcomp
VIEWWORKORDER_USER_CL_PREFIX=wfcls
EOF

# PID 1 is `sleep infinity`; writing here shows up in `oc logs`.
emit() {
  if [[ -w /proc/1/fd/1 ]]; then
    tee /proc/1/fd/1
  else
    cat
  fi
}

export HEAP="-Xms${HEAP} -Xmx${HEAP}"
{
  echo "IBM MAS-Manage-UI  domain=${MAS_DOMAIN} workspace=${MAS_WORKSPACE} duration=${DURATION_S}s"
  echo "JTL ${OUT}"
} | emit

rc=0
timeout -s INT "${DURATION_S}" jmeter -n \
  -t /opt/benchmark/MAS-Manage-UI.jmx \
  -q "$PROPS" \
  -l "$OUT" \
  -j "$LOG" || rc=$?
# 124 = GNU timeout stopped JMeter after DURATION_S (expected).
if [[ "$rc" -ne 0 && "$rc" -ne 124 ]]; then
  echo "jmeter/timeout exited ${rc}" | emit
  exit "$rc"
fi

{
  echo "===== JTL summary ====="
  python3 /opt/benchmark/summarize_jtl.py "$OUT" || true
  echo "===== log tail ====="
  tail -n 40 "$LOG" || true
  echo "results: ${OUT}  ${LOG}"
} | emit
